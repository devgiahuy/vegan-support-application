import { RecipeDifficulty } from '@prisma/client';

export interface SeedRecipeStep {
  position: number;
  instruction: string;
  cookingMethodCode?: string;
  durationMinutes: number;
  affectedIngredientPositions: number[];
}

export interface SeedRecipeIngredient {
  ingredientNormalizedName: string;
  displayName: string;
  amount: number;
  unit: string;
}

export interface SeedImageCredit {
  title: string;
  author: string;
  license: string;
  licenseUrl: string;
  sourceUrl: string;
}

export interface SeedRecipeCover {
  publicId: string;
  secureUrl: string;
  width: number;
  height: number;
  bytes: number;
  /** Present only for openly licensed images; local legacy files have unverified provenance. */
  credit?: SeedImageCredit;
}

/**
 * Seed recipes. Calories, macros, allergen codes, tradition warnings and diet compatibility are
 * derived in the seeder from the canonical ingredient catalogue (USDA FoodData Central values),
 * so they cannot drift from the ingredient list. Amounts are raw, as-purchased weights; grains and
 * legumes are listed dry. `coverMedia: null` means no suitably licensed photo was found yet
 * (see docs/SEED_NUTRITION_RECIPE_DATA.md for the manual image list).
 */
export interface SeedRecipeDefinition {
  slug: string;
  title: string;
  excerpt: string;
  body: string;
  categorySlug: string;
  authorEmail: string;
  tags: string[];
  servings: number;
  prepTimeMinutes: number;
  cookTimeMinutes: number;
  difficulty: RecipeDifficulty;
  mealPlannerEligible: boolean;
  ingredients: SeedRecipeIngredient[];
  steps: SeedRecipeStep[];
  coverMedia: SeedRecipeCover | null;
}

